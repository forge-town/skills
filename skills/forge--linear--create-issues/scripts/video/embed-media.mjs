// Embed user-supplied audio into js/data/media.js as data URIs so the video folder plays from file://.
// Keys are the src strings used in story.js (narration[].src or music.src). Only embed media you may redistribute.
// Usage: node scripts/video/embed-media.mjs <video-dir> <audio-file>... (src key = path relative to <video-dir>)
import { readFileSync, writeFileSync } from 'node:fs';
import { extname, join, relative, resolve } from 'node:path';

const TYPES = { '.mp3': 'audio/mpeg', '.m4a': 'audio/mp4', '.aac': 'audio/aac', '.wav': 'audio/wav', '.ogg': 'audio/ogg', '.opus': 'audio/ogg', '.flac': 'audio/flac' };
const [dir, ...files] = process.argv.slice(2);
if (!dir || !files.length) { console.error('Usage: embed-media.mjs <video-dir> <audio-file>...'); process.exit(2); }
const media = {};
for (const f of files) {
  const type = TYPES[extname(f).toLowerCase()];
  if (!type) { console.error(`Unsupported audio type: ${f}`); process.exit(1); }
  media[relative(resolve(dir), resolve(f)).split('\\').join('/')] = `data:${type};base64,${readFileSync(f).toString('base64')}`;
}
const body = Object.entries(media).map(([k, v]) => `  HV.media[${JSON.stringify(k)}] = ${JSON.stringify(v)};`).join('\n');
writeFileSync(join(dir, 'js/data/media.js'), `// Generated by embed-media.mjs\n(function (root) {\n  const HV = root.HV = root.HV || {};\n  HV.media = HV.media || {};\n${body}\n})(typeof window !== 'undefined' ? window : globalThis);\n`);
console.log(`Embedded ${files.length} file(s) into ${join(dir, 'js/data/media.js')}: ${Object.keys(media).join(', ')}`);
